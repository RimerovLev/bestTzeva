const BY_CODE = new Map(RAL_CLASSIC.map(([c, h]) => [c, h]));
export const ralHex = (code: string) => BY_CODE.get(code);

const lin = (c: number) => { const v = c / 255; return v <= 0.04045 ? v / 12.92 : Math.pow((v + 0.055) / 1.055, 2.4); };
const f = (t: number) => (t > 0.008856 ? Math.cbrt(t) : 7.787 * t + 16 / 116);
function lab(hex: string): [number, number, number] {
  const r = lin(parseInt(hex.slice(1, 3), 16)), g = lin(parseInt(hex.slice(3, 5), 16)), b = lin(parseInt(hex.slice(5, 7), 16));
  const x = f((0.4124 * r + 0.3576 * g + 0.1805 * b) / 0.95047), y = f(0.2126 * r + 0.7152 * g + 0.0722 * b), z = f((0.0193 * r + 0.1192 * g + 0.9505 * b) / 1.08883);
  return [116 * y - 16, 500 * (x - y), 200 * (y - z)];
}
const LABS = RAL_CLASSIC.map(([c, h]) => [c, lab(h)] as const);

/** Ближайший RAL к произвольному цвету (ΔE76 в Lab) — чтобы любой выбранный цвет можно было назвать кодом. */
export function nearestRal(hex: string): { code: string; hex: string; deltaE: number } {
  const [l, a, b] = lab(hex);
  let best = LABS[0]!, bd = Infinity;
  for (const e of LABS) {
    const d = Math.hypot(e[1][0] - l, e[1][1] - a, e[1][2] - b);
    if (d < bd) { bd = d; best = e; }
  }
  return { code: best[0], hex: BY_CODE.get(best[0])!, deltaE: bd };
}
