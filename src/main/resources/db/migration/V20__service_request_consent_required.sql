-- ─────────────────────────────────────────────────────────────────────────────
-- R-19: обязательность согласия закрепляется в схеме.
--
-- 1) service_requests.consent_given_at → not null. Требование T-11.1: без согласия
--    заявка не принимается. Форма собирает адрес и фото жилья — соответствие
--    израильскому закону о приватности не может держаться только на коде
--    контроллера (не переживёт импорт, ручную вставку, второй путь создания).
-- 2) consents.policy_version — версия редакции текста согласия (T-14.2): нужно
--    фиксировать, на какую именно редакцию пользователь согласился. Nullable,
--    т.к. заполняется по мере появления версий политики.
-- ─────────────────────────────────────────────────────────────────────────────

alter table service_requests alter column consent_given_at set not null;

alter table consents add column policy_version varchar(32);
