-- R-29: коды купонов регистронезависимы. Уникальность была по code как есть —
-- клиент, набравший summer10 вместо SUMMER10, купон бы не получил, а админ мог
-- завести два купона, отличающихся только регистром. Переходим на уникальный
-- индекс по lower(code) (как users.email); поиск купона тоже по lower.
-- ─────────────────────────────────────────────────────────────────────────────

alter table coupons drop constraint uq_coupons_code;

create unique index uq_coupons_code on coupons (lower(code));
