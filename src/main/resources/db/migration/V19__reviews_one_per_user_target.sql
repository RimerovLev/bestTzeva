-- R-18: один отзыв на пару пользователь + объект (товар/услуга).
-- Правило T-10.2 (повтор — 409) существовало только в коде и проигрывало бы
-- гонке двух одновременных отправок: в базе оказывались два отзыва одного
-- пользователя, оба влияющие на rating_avg. Частичный уникальный индекс: только
-- для отзывов с user_id (анонимные, где user_id null, не ограничиваются).
-- ─────────────────────────────────────────────────────────────────────────────

create unique index uq_reviews_user_target
    on reviews (user_id, target_type, target_id)
    where user_id is not null;
