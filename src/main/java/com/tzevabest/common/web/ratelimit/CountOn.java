package com.tzevabest.common.web.ratelimit;

/**
 * Что засчитывать в бюджет {@link RateLimit}.
 * <ul>
 *   <li>{@link #ALL} — каждый вызов (проверка и запись атомарны, обычный лимит частоты);</li>
 *   <li>{@link #FAILURE} — только вызовы, завершившиеся исключением: аспект проверяет бюджет до
 *       вызова, но запись в окно делает лишь если метод бросил (напр. неверные учётные данные).
 *       Успешные вызовы бюджет не тратят.</li>
 * </ul>
 */
public enum CountOn {
    ALL,
    FAILURE
}
